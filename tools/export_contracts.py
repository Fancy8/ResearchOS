"""Deterministic OpenAPI and TypeScript schema artifacts, usable offline."""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from app.main import app


def typescript(schema):
    if "$ref" in schema:
        return f"components[{json.dumps(schema['$ref'].rsplit('/', 1)[-1])}]"
    if "enum" in schema:
        return " | ".join(
            json.dumps(value, ensure_ascii=False) for value in schema["enum"]
        )
    alternatives = schema.get("anyOf") or schema.get("oneOf")
    if alternatives:
        return " | ".join(typescript(value) for value in alternatives)
    if schema.get("allOf"):
        return " & ".join(typescript(value) for value in schema["allOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{typescript(schema.get('items', {}))}>"
    if kind == "object" or "properties" in schema:
        properties, required = schema.get("properties", {}), schema.get("required", [])
        if properties:
            return (
                "{ "
                + " ".join(
                    f"{json.dumps(key)}{'' if key in required else '?'}: {typescript(value)};"
                    for key, value in properties.items()
                )
                + " }"
            )
        additional = schema.get("additionalProperties")
        return f"Record<string, {typescript(additional) if isinstance(additional, dict) else 'unknown'}>"
    return {
        "string": "string",
        "number": "number",
        "integer": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    specification = app.openapi()
    content = (
        json.dumps(specification, ensure_ascii=False, sort_keys=True, indent=2) + "\n"
    )
    definitions = specification["components"]["schemas"]
    generated = (
        "// Generated by tools/export_contracts.py. Do not edit by hand.\nexport interface components {\n"
        + "\n".join(
            f"  {json.dumps(name)}: {typescript(schema)};"
            for name, schema in sorted(definitions.items())
        )
        + "\n}\n"
    )
    outputs = {
        ROOT / "contracts/openapi.json": content,
        ROOT / "frontend/src/lib/generated-contracts.ts": generated,
    }
    for path, value in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != value:
                raise SystemExit(f"Contract drift: {path.relative_to(ROOT)}")
        else:
            path.write_text(value, encoding="utf-8")
    print(
        f"Contracts {'verified' if args.check else 'generated'}: {len(specification['paths'])} paths, {len(definitions)} schemas"
    )


if __name__ == "__main__":
    main()
