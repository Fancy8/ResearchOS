"""Bounded artifact expiry and orphan reconciliation; research history is retained."""

import json
import time
from datetime import UTC, datetime, timedelta
from uuid import UUID

from sqlalchemy import exists, select, text
from sqlalchemy.orm import sessionmaker

from app.core.config import get_settings
from app.core.resource_locks import exclusive_resource
from app.core.storage import s3_client
from app.models import ExportJob, MaintenanceCheckpoint, PaperFile, ProcessingJob, UploadSession, Workspace
from app.workers.celery_app import celery_app
from app.workers.deletions import cleanup_engine, remove_prefix
from app.workers.reconciliation import reconcile_objects, reconcile_temp


def expire_workspace(db, workspace_id, now, storage=None, bucket=None, batch_size=100):
    counts = {"exports_expired": 0, "uploads_expired": 0}
    workspace = db.get(Workspace, workspace_id)
    if not workspace or workspace.status != "active":
        return counts
    for job in db.scalars(
        select(ExportJob)
        .where(
            ExportJob.workspace_id == workspace_id,
            ExportJob.status == "succeeded",
            ExportJob.expires_at <= now,
        )
        .order_by(ExportJob.expires_at, ExportJob.id)
        .limit(batch_size)
    ):
        # Remove all attempts/versions for this exact job, retaining its status/history.
        remove_prefix(f"exports/{workspace_id}/{job.id}-", storage=storage, bucket=bucket)
        job.status, job.storage_key = "expired", None
        job.attempt_token = job.lease_owner = job.lease_expires_at = None
        counts["exports_expired"] += 1
    active_parser = exists().where(
        ProcessingJob.paper_file_id == UploadSession.paper_file_id,
        ProcessingJob.status.in_(["queued", "running"]),
    )
    for upload in db.scalars(
        select(UploadSession)
        .where(
            UploadSession.workspace_id == workspace_id,
            UploadSession.status == "pending",
            UploadSession.expires_at <= now,
            ~active_parser,
        )
        .order_by(UploadSession.expires_at, UploadSession.id)
        .limit(batch_size)
    ):
        file = db.get(PaperFile, upload.paper_file_id)
        if not file or file.upload_status != "pending":
            continue
        # The staging key is generated by our upload service, not taken from the caller.
        expected = f"staging/{workspace_id}/{upload.id}.pdf"
        if upload.staging_key != expected:
            raise RuntimeError("UPLOAD_STAGING_SCOPE_INVALID")
        remove_prefix(upload.staging_key, storage=storage, bucket=bucket)
        upload.status = "expired"
        upload.lease_token = upload.lease_expires_at = None
        file.upload_status, file.parse_status, file.availability_status, file.is_current = (
            "failed",
            "failed",
            "missing",
            False,
        )
        counts["uploads_expired"] += 1
    return counts


def read_checkpoint(db, name, bucket):
    checkpoint = db.get(MaintenanceCheckpoint, name)
    if not checkpoint or checkpoint.state.get("bucket") != bucket:
        return {"bucket": bucket}
    state = dict(checkpoint.state)
    if name == "artifact-maintenance" and checkpoint.workspace_id:
        state["workspace_after"] = str(checkpoint.workspace_id)
    return state


def save_checkpoint(db, name, state, now, workspace_id=None):
    payload = dict(state)
    if name == "artifact-maintenance":
        following = payload.pop("workspace_after", None)
        workspace_id = UUID(following) if following else None
    checkpoint = db.get(MaintenanceCheckpoint, name)
    if not checkpoint:
        checkpoint = MaintenanceCheckpoint(name=name, workspace_id=workspace_id)
        db.add(checkpoint)
    # The global cursor also uses the FK: deleting its last workspace removes
    # the checkpoint atomically rather than retaining a bare identity in JSON.
    checkpoint.workspace_id = workspace_id
    checkpoint.state, checkpoint.updated_at = payload, now


def maintenance_once(*, storage=None, bucket=None, batch_size=100, now=None):
    if not 1 <= batch_size <= 500:
        raise ValueError("INVALID_EXPIRY_BATCH_SIZE")
    engine, now = cleanup_engine(), now or datetime.now(UTC)
    if now.tzinfo is None:
        raise ValueError("MAINTENANCE_CLOCK_MUST_HAVE_TIMEZONE")
    settings = get_settings()
    storage, bucket = storage or s3_client(), bucket or settings.s3_bucket
    cutoff = now - timedelta(hours=settings.orphan_grace_hours)
    deadline = time.monotonic() + settings.maintenance_cycle_seconds
    Sessions = sessionmaker(engine)
    report = {
        "exports_expired": 0,
        "uploads_expired": 0,
        "workspaces_failed": 0,
        "workspaces_busy": 0,
        "workspaces_visited": 0,
        "orphan_objects_removed": 0,
        "orphan_bytes_removed": 0,
        "unrecognized_objects": 0,
        "temporary_files_removed": 0,
        "temporary_bytes_removed": 0,
        "temporary_files_busy": 0,
        "temporary_files_blocked": 0,
        "temporary_scan_failed": 0,
    }
    with engine.connect().execution_options(isolation_level="AUTOCOMMIT") as leader:
        acquired = leader.execute(
            text("SELECT pg_try_advisory_lock(hashtextextended('maintenance-expiry',0))")
        ).scalar()
        if not acquired:
            return {**report, "already_running": True}
        try:
            with Sessions() as db:
                if db.execute(text("SELECT current_user")).scalar_one() != "researchos_cleanup":
                    raise RuntimeError("EXPIRY_REQUIRES_CLEANUP_ROLE")
                state = read_checkpoint(db, "artifact-maintenance", bucket)
                query = (
                    select(Workspace.id)
                    .where(Workspace.status == "active")
                    .order_by(Workspace.id)
                    .limit(min(batch_size, 20))
                )
                following = UUID(state["workspace_after"]) if state.get("workspace_after") else None
                identifiers = list(db.scalars(query.where(Workspace.id > following) if following else query))
                if not identifiers and following:
                    identifiers = list(db.scalars(query))
            for workspace_id in identifiers:
                if time.monotonic() >= deadline:
                    break
                report["workspaces_visited"] += 1
                try:
                    with exclusive_resource(engine, workspace_id, wait=False) as acquired:
                        if not acquired:
                            report["workspaces_busy"] += 1
                            continue
                        with Sessions.begin() as db, db.no_autoflush:
                            checkpoint_name = f"artifact-reconcile/{workspace_id}"
                            workspace_state = read_checkpoint(db, checkpoint_name, bucket)
                            counts = expire_workspace(db, workspace_id, now, storage, bucket, batch_size)
                            counts.update(
                                reconcile_objects(
                                    db,
                                    workspace_id,
                                    storage,
                                    bucket,
                                    workspace_state,
                                    now,
                                    cutoff,
                                    batch_size,
                                )
                            )
                            save_checkpoint(db, checkpoint_name, workspace_state, now, workspace_id)
                        for name, count in counts.items():
                            report[name] += count
                except Exception:
                    # The transaction remains uncommitted; the next tick retries missing bytes safely.
                    report["workspaces_failed"] += 1
                finally:
                    # Busy/failed spaces cannot indefinitely starve later spaces.
                    state["workspace_after"] = str(workspace_id)
                    with Sessions.begin() as db:
                        save_checkpoint(db, "artifact-maintenance", state, now)
            try:
                if time.monotonic() < deadline:
                    counts = reconcile_temp(engine, Sessions, engine.url.database, state, cutoff, batch_size)
                    for name, count in counts.items():
                        report[name] += count
                    with Sessions.begin() as db:
                        save_checkpoint(db, "artifact-maintenance", state, now)
            except Exception:
                report["temporary_scan_failed"] += 1
        finally:
            leader.execute(text("SELECT pg_advisory_unlock(hashtextextended('maintenance-expiry',0))"))
    return report


@celery_app.task(name="researchos.expire_artifacts")
def expire_artifacts():
    try:
        report = maintenance_once()
    except Exception:
        report = {"error_code": "MAINTENANCE_UNAVAILABLE"}
    if any(value for key, value in report.items() if key != "workspaces_visited"):
        print(json.dumps({"event": "artifact_expiry", **report}, sort_keys=True), flush=True)
    return report
